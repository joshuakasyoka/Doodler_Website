/**
 * Copy audit: proves every piece of copy in the original HTML is present,
 * unaltered, in /content.
 *
 *   npm run copy:audit [-- <original-site-dir>]   (default: assets-source/original-site)
 *
 * For every text block (heading, paragraph, list item, link, button…) and every
 * alt / aria-label / placeholder / title / meta description in the original
 * pages, it checks that the exact text appears in a content field (markup
 * stripped, whitespace normalised). Writes COPY-AUDIT.md and exits 1 on any miss.
 */
import fs from "node:fs";
import path from "node:path";
import * as content from "@/content";
import { stripMarkup } from "@/lib/content/markup";

const dir = process.argv[2] ?? "assets-source/original-site";
// team.html was only a meta-refresh stub; it is now a 301 redirect (next.config.ts)
const SKIP_FILES = new Set(["team.html"]);

const BLOCK = new Set([
  "title",
  "h1",
  "h2",
  "h3",
  "h4",
  "p",
  "li",
  "blockquote",
  "figcaption",
  "a",
  "button",
  "label",
  "strong",
  "small",
  "span",
  "em",
  "div",
  "summary",
  "dt",
  "dd",
]);
const SKIP_TAGS = new Set(["script", "style", "svg", "noscript"]);
const VOID = new Set(["img", "br", "meta", "link", "source", "input", "hr", "wbr"]);

const decode = (s: string) =>
  s
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&#(\d+);/g, (_, n: string) => String.fromCodePoint(Number(n)));
const norm = (s: string) => decode(s).replace(/\s+/g, " ").trim();

type Found = { kind: string; text: string; runs: string[] };

function extract(html: string): Found[] {
  const found: Found[] = [];
  const title = html.match(/<title[^>]*>([\s\S]*?)<\/title>/);
  if (title?.[1]) found.push({ kind: "title", text: norm(title[1]), runs: [] });
  const desc = html.match(/<meta name="description" content="([^"]*)"/);
  if (desc?.[1]) found.push({ kind: "meta description", text: norm(desc[1]), runs: [] });

  const body = html.slice(html.indexOf("<body"));
  const stack: { tag: string; text: string[]; runs: string[] }[] = [];
  let skip = 0;
  const re = /<!--[\s\S]*?-->|<\/?([a-zA-Z0-9]+)([^>]*)>|([^<]+)/g;
  for (const m of body.matchAll(re)) {
    const [whole, tagName, attrs = "", textNode] = m;
    if (whole.startsWith("<!--")) continue;
    if (textNode !== undefined) {
      if (skip) continue;
      const t = norm(textNode);
      if (!t) {
        stack.forEach((s) => s.text.push(" "));
        continue;
      }
      stack.forEach((s) => {
        s.text.push(textNode);
        s.runs.push(t);
      });
      continue;
    }
    const tag = (tagName ?? "").toLowerCase();
    const closing = whole.startsWith("</");
    if (SKIP_TAGS.has(tag)) {
      if (closing) skip = Math.max(0, skip - 1);
      else if (!whole.endsWith("/>")) skip++;
      continue;
    }
    if (skip) continue;
    if (!closing) {
      for (const attr of ["alt", "aria-label", "placeholder", "title"]) {
        const a = attrs.match(new RegExp(`\\s${attr}="([^"]*)"`));
        if (a?.[1] && norm(a[1])) found.push({ kind: attr, text: norm(a[1]), runs: [] });
      }
      if (!VOID.has(tag) && !whole.endsWith("/>")) stack.push({ tag, text: [], runs: [] });
    } else {
      const idx = stack.map((s) => s.tag).lastIndexOf(tag);
      if (idx === -1) continue;
      const [el] = stack.splice(idx, stack.length - idx);
      if (!el || !BLOCK.has(tag)) continue;
      const text = norm(el.text.join(""));
      if (text) found.push({ kind: tag, text, runs: el.runs });
    }
  }
  return found;
}

// every string value anywhere in /content, markup stripped
const corpus: string[] = [];
const collect = (node: unknown): void => {
  if (typeof node === "string") {
    corpus.push(norm(stripMarkup(node)));
    corpus.push(norm(node));
  } else if (Array.isArray(node)) node.forEach(collect);
  else if (node && typeof node === "object") Object.values(node).forEach(collect);
};
collect(content.site);
collect(content.pages);
const haystack = corpus.join("\n");
const has = (s: string) => haystack.includes(s);

const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".html") && !SKIP_FILES.has(f))
  .sort();
const lines: string[] = [
  "# Copy audit",
  "",
  `Source: \`${dir}\` (${files.length} pages). Generated by \`npm run copy:audit\`.`,
  "",
  "✓ exact = the whole block appears verbatim in one content field.",
  "✓ split = the block is split over several fields (e.g. a figure and its caption); every text run appears verbatim.",
  "",
];
let total = 0;
let missing = 0;
for (const file of files) {
  const seen = new Set<string>();
  const items = extract(fs.readFileSync(path.join(dir, file), "utf8")).filter((f) => {
    const key = `${f.kind}|${f.text}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  lines.push(`## ${file}`, "", "| | Kind | Text |", "|---|---|---|");
  for (const item of items) {
    // skip container blocks whose text is exactly the sum of child blocks already listed
    if (item.kind === "div" && has(item.text) === false && item.runs.every(has)) continue;
    total++;
    let status: string;
    if (has(item.text)) status = "✓ exact";
    else if (item.runs.length > 1 && item.runs.every(has)) status = "✓ split";
    else {
      status = "✗ MISSING";
      missing++;
    }
    if (item.kind === "div" && status !== "✗ MISSING") {
      total--;
      continue;
    }
    lines.push(`| ${status} | ${item.kind} | ${item.text.replace(/\|/g, "\\|")} |`);
  }
  lines.push("");
}
lines.splice(3, 0, `**${total - missing} / ${total} strings present. ${missing} missing.**`, "");
fs.writeFileSync("COPY-AUDIT.md", lines.join("\n"));
console.log(`copy audit: ${total - missing}/${total} present, ${missing} missing → COPY-AUDIT.md`);
if (missing) process.exit(1);
